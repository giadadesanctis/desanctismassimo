const imageUrl = (source) => source.startsWith("http")
  ? source
  : source.startsWith("images/")
    ? source
    : `https://images.unsplash.com/${source}?auto=format&fit=crop&w=1800&q=85`;
let currentLanguage = "it";

function setLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = dictionary["page.title"];
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation) element.innerHTML = translation;
  });
  document.querySelectorAll(".language-switch [data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", dictionary[element.dataset.i18nAriaLabel]);
  });
  document.querySelectorAll(".carousel").forEach((carousel) => {
    const paused = carousel.dataset.paused === "true";
    const toggle = carousel.querySelector(".carousel-toggle");
    toggle.textContent = dictionary[paused ? "carousel.play" : "carousel.pause"];
    carousel.querySelector(".previous").setAttribute("aria-label", dictionary["carousel.previous"]);
    carousel.querySelector(".next").setAttribute("aria-label", dictionary["carousel.next"]);
  });
  document.querySelectorAll(".carousel").forEach((carousel) => updateCarousel(carousel));
}

function updateCarousel(carousel) {
  const slides = galleryImages[carousel.dataset.carousel];
  const index = Number(carousel.dataset.index || 0);
  const slide = slides[index];
  const image = carousel.querySelector(".carousel-image");
  image.src = imageUrl(slide.image);
  image.alt = slide.titles[currentLanguage];
  carousel.querySelector(".carousel-number").textContent = `${String(index + 1).padStart(2, "0")} / ${String(slides.length).padStart(2, "0")}`;
  carousel.querySelector(".carousel-title").textContent = slide.titles[currentLanguage];
  carousel.querySelector(".carousel-description").textContent = slide.descriptions[currentLanguage];
  carousel.querySelectorAll(".carousel-dot").forEach((dot, dotIndex) => {
    dot.setAttribute("aria-current", String(dotIndex === index));
    dot.setAttribute("aria-label", `${dotIndex + 1} / ${slides.length}`);
  });
}

function goToSlide(carousel, index) {
  const slides = galleryImages[carousel.dataset.carousel];
  carousel.dataset.index = String((index + slides.length) % slides.length);
  updateCarousel(carousel);
}

function startCarousel(carousel) {
  if (carousel.dataset.paused === "true" || (window.matchMedia("(prefers-reduced-motion: reduce)").matches && carousel.dataset.motionEnabled !== "true")) return;
  window.clearInterval(carousel.carouselTimer);
  carousel.carouselTimer = window.setInterval(() => {
    if (!document.hidden) goToSlide(carousel, Number(carousel.dataset.index || 0) + 1);
  }, 5200);
}

document.querySelectorAll(".carousel").forEach((carousel) => {
  const progress = carousel.querySelector(".carousel-progress");
  galleryImages[carousel.dataset.carousel].forEach((_, index) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.className = "carousel-dot";
    dot.addEventListener("click", () => {
      goToSlide(carousel, index);
      startCarousel(carousel);
    });
    progress.append(dot);
  });
  carousel.querySelector(".previous").addEventListener("click", () => {
    goToSlide(carousel, Number(carousel.dataset.index || 0) - 1);
    startCarousel(carousel);
  });
  carousel.querySelector(".next").addEventListener("click", () => {
    goToSlide(carousel, Number(carousel.dataset.index || 0) + 1);
    startCarousel(carousel);
  });
  const toggle = carousel.querySelector(".carousel-toggle");
  toggle.addEventListener("click", () => {
    const paused = carousel.dataset.paused !== "true";
    carousel.dataset.paused = String(paused);
    if (!paused) carousel.dataset.motionEnabled = "true";
    toggle.setAttribute("aria-pressed", String(paused));
    toggle.textContent = translations[currentLanguage][paused ? "carousel.play" : "carousel.pause"];
    if (paused) window.clearInterval(carousel.carouselTimer);
    else startCarousel(carousel);
  });
  carousel.addEventListener("mouseenter", () => window.clearInterval(carousel.carouselTimer));
  carousel.addEventListener("mouseleave", () => startCarousel(carousel));
  carousel.addEventListener("focusin", () => window.clearInterval(carousel.carouselTimer));
  carousel.addEventListener("focusout", () => startCarousel(carousel));
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    carousel.dataset.paused = "true";
    const toggle = carousel.querySelector(".carousel-toggle");
    toggle.setAttribute("aria-pressed", "true");
    toggle.textContent = translations[currentLanguage]["carousel.play"];
  }
  updateCarousel(carousel);
  startCarousel(carousel);
});

document.querySelectorAll(".language-switch [data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const menuToggle = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");
menuToggle.addEventListener("click", () => {
  const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isExpanded));
  menuToggle.setAttribute("aria-label", translations[currentLanguage][isExpanded ? "menu.open" : "menu.close"]);
  siteNav.classList.toggle("is-open", !isExpanded);
});
siteNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", translations[currentLanguage]["menu.open"]);
    siteNav.classList.remove("is-open");
  });
});
